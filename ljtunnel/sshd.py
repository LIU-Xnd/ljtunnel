def _penalties() -> str:
    """The penalty settings, for the config.

    WINDOWS ONLY, AND IT MATTERS MORE THAN IT LOOKS.

    OpenSSH for Windows 10.0 has PerSourcePenalties on by default.
    It is a defence against a machine that opens many connections
    and does not authenticate them -- and the tunnel's OWN dialer
    does exactly that, because it CHECKS the ports it asks for by
    connecting to them.

    So a dialer that tries a few ports can put its own address into
    the penalty list, and then:

        Not allowed at this time

    is what the sshd sends -- instead of a banner.  The client sees
    a line that is not an SSH banner and gives up with "banner line
    contains invalid characters", and the sshd's log blames the
    banner rather than the penalty.  That cost an afternoon.

    The penalty is a good idea and it stays on.  But the tunnel's own
    machine is EXEMPT: the dialer may be on the same machine as the
    listen end (a test does exactly that), and a tunnel must not
    lock ITSELF out.
    """
    if sys.platform != "win32":
        return ""

    # The exemption is by ADDRESS, and the addresses that matter are
    # the loopback and this end's own -- the ones the tunnel itself
    # uses.  A dialer on another machine is not exempt, and the
    # penalty still protects the listen end from a dialer that
    # misbehaves.
    exempt = ["127.0.0.1", "::1"]
    try:
        import socket
        own = socket.gethostbyname(socket.gethostname())
        if own and own != "127.0.0.1":
            exempt.append(own)
    except OSError:
        pass

    return (
        "\n# The per-source penalty is ON, and the tunnel's own\n"
        "# addresses are exempt from it.  A dialer CHECKS the ports\n"
        "# it asks for by connecting to them, which is exactly what\n"
        "# the penalty is for -- so without the exemption the tunnel\n"
        "# locks ITSELF out, and the sshd says 'Not allowed at this\n"
        "# time' where a banner should be.\n"
        "PerSourcePenaltyExemptList " + ",".join(exempt) + "\n"
    )


def write_config(port: int, listen: str = "0.0.0.0",
                 gateway_ports: bool = False,
                 allow_forwarding: bool = False,
                 permit_listen: list = None,
                 host_key: str = "",
                 log_level: str = "INFO") -> str:
    """Render the sshd config and return its path.

    permit_listen is the set of ports a dialer may ask to be given.
    They go on ONE line, space separated, because sshd keeps only the
    LAST PermitListen line: twenty lines would leave one port.
    A range (10002-10021) is not accepted -- PermitListen takes a
    single port, on Windows and on Linux alike.

    host_key is the key file this sshd presents.  It is the HOST
    key by default, and the DIALER end passes its MACHINE key
    instead -- and that is not tidiness:

    The listen end finds its dialers by asking the forwarded port
    who is there, and the answer is the host key behind it.  So the
    host key behind a forwarded port has to be a key the listen end
    KNOWS, and the only key it knows is the one the dialer logged in
    with.  So the dialer's sshd presents its machine key as its host
    key, and the two are the same key.

    One key, two jobs: the dialer's identity to the listen end, and
    the dialer's identity to whoever connects to the forwarded port.
    And it is still one key on disk.
    """
    paths.ensure_dir(paths.state_dir())
    # The paths in the config are ABSOLUTE, and they are the ones
    # this end really uses.  The state directory is not always under
    # the home directory -- XDG_STATE_HOME can put it anywhere -- and
    # a config that names a path the sshd does not use is a config
    # whose key list is never read.
    if permit_listen:
        ports = " ".join(str(p) for p in permit_listen)
        permit = ("\n# The ports a dialer may be given, on ONE line: sshd\n"
                  "# keeps only the last PermitListen line.\n"
                  f"PermitListen {ports}\n")
    else:
        permit = ""
    body = _TEMPLATE.format(
        port=port,
        listen=listen,
        log_level=log_level,
        host_key=_for_sshd(host_key or paths.host_key()),
        pid_file=_for_sshd(paths.pid_file()),
        authorized_keys=_for_sshd(paths.authorized_keys()),
        win_only=("UsePrivilegeSeparation no\n"
                 if sys.platform == "win32" else ""),
        gateway=("GatewayPorts clientspecified\n"
                 if gateway_ports else ""),
        forwarding=("AllowTcpForwarding remote\n"
                    if allow_forwarding else
                    "AllowTcpForwarding no\n"),
        permit_listen=permit,
        penalties=_penalties(),
    )
    path = paths.sshd_config()
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return path


def _for_sshd(path: str) -> str:
    """The path as the sshd wants to read it.

    On Windows the sshd is a C program, and a C program that opens a
    file with a backslash in the name treats the backslash as an
    escape in some code paths.  Forward slashes work on both
    platforms and are what the path means anyway.
    """
    return path.replace("\\", "/")


def ensure_host_key() -> str:
    """Make this end's host key if it does not have one.

    The key is the identity a client sees when it connects, so it has
    to SURVIVE a restart: a new key every time would make every
    client complain about a changed host key.
    """
    key = paths.host_key()
    if os.path.isfile(key):
        return key
    paths.ensure_dir(paths.state_dir())
    r = subprocess.run(
        [ssh_keygen_path(), "-q", "-t", "ed25519", "-f", key, "-N", ""],
        capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        raise SystemExit(f"ssh-keygen failed: {(r.stdout + r.stderr).strip()}")
    try:
        os.chmod(key, 0o600)
    except OSError:
        pass
    return key


