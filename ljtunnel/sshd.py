def public_key_of(key: str) -> str:
    """The public key text for a private key path."""
    with open(key + ".pub", "r", encoding="utf-8") as fh:
        return fh.read().strip()


def set_authorized_keys(lines: list) -> str:
    """Write the key list this end's sshd will accept."""
    paths.ensure_dir(paths.state_dir())
    path = paths.authorized_keys()
    body = "".join(l.rstrip() + "\n" for l in lines if l.strip())
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return path


def start(port: int, listen: str = "0.0.0.0",
          gateway_ports: bool = False,
          allow_forwarding: bool = False,
          permit_listen: list = None,
          host_key: str = "",
          log_level: str = "INFO",
          on_log=None) -> subprocess.Popen:
    """Start this end's sshd, and return the process.

    -D keeps it in the foreground, so the caller owns it and can stop
    it. A backgrounded sshd would be a process nobody could find.

    A previous run's sshd is stopped FIRST. Otherwise the new one dies
    with "Address already in use" and nothing says who holds the port
    -- and the process holding it has usually changed its title to
    "sshd: /usr/sbin/sshd -f ...", so a pkill on the config path does
    not find it. The pid file is the reliable handle.

    THE LOG GOES DOWN A PIPE, NOT TO A FILE
    -----------------------------------------
    On Windows, `-E <file>` holds the log file EXCLUSIVELY: it cannot
    be read by python, by `cmd /c type`, or by `copy`.  A log nobody
    can read is no log at all, and the listen end needs to read it --
    it is where the dialers' names and ports come from.

    So the log goes to STDERR (`-e`) and the parent reads it off a
    pipe.  The parent writes it to the log file AND hands each line to
    the on_log callback, so the file is there for a person to look at
    and the callback is there for the code to use.

    Linux has no `-E` at all, so `-e` is the only way there too.  The
    two ends of this are the same code, which is the point.
    """
    stop()

    ensure_host_key()
    if not os.path.isfile(paths.authorized_keys()):
        set_authorized_keys([])
    cfg = write_config(port, listen, gateway_ports, allow_forwarding,
                       permit_listen, host_key, log_level)

    cmd = [sshd_path(), "-f", cfg, "-D", "-e"]
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT,
                         text=True, errors="replace", bufsize=1)

    _pump_log(p, on_log)
    return p


def _pump_log(proc, on_log=None) -> None:
    """Read the sshd's log off the pipe, and keep it.

    A child whose stdout is a pipe must have that pipe drained, or the
    child blocks on a full buffer and never exits.  So this thread
    runs for the life of the sshd.

    The lines are written to the log file as they arrive, so a person
    who opens the file while the sshd is running sees what has
    happened so far, and not just what happened at the end.
    """
    import threading

    def _run():
        try:
            with open(paths.log_file(), "a", encoding="utf-8",
                      errors="replace", newline="\n") as fh:
                for line in proc.stdout:
                    fh.write(line)
                    fh.flush()
                    if on_log:
                        try:
                            on_log(line.rstrip("\n"))
                        except Exception:
                            # A callback that raises must not take the
                            # log down with it: the log is the record
                            # of what sshd did.
                            pass
        except (OSError, ValueError):
            pass
        finally:
            try:
                proc.stdout.close()
            except Exception:
                pass

    t = threading.Thread(target=_run, daemon=True,
                         name="ljtunnel-sshd-log")
    t.start()
    return t


def stop() -> bool:
    """Stop this end's sshd, if it is running.

    The pid file is where the answer is: the process is ours, we
    started it, and sshd wrote the file. Guessing from the process
    list would risk killing the SYSTEM sshd -- which is a real service
    on port 22 and must never be touched by this.

    On Linux sshd FORKS: the process that was started writes the pid
    file and exits, and the LISTENER is a different process. So the
    pid file names the listener and that is the one to kill. The
    process title is also "sshd: /usr/sbin/sshd -f ...", which is why
    a pkill on the config path does not find it.
    """
    pidfile = paths.pid_file()
    if not os.path.isfile(pidfile):
        # NO PID FILE, BUT THERE MAY STILL BE AN ORPHAN.
        #
        # The pid file is where the answer usually is, and it is
        # right every time it is there.  But a test that removes the
        # state directory leaves a process behind with nothing to
        # name it, and it goes on holding the port -- and the next
        # launch says the port is busy for no reason anybody can
        # see.
        #
        # MEASURED: a leftover sshd on 10000, with no pid file, and
        # `stop()` said "not running" and left it there.
        #
        # So the orphans are found by their COMMAND LINE, which
        # names this project's config -- never by the image name,
        # because the SYSTEM sshd is a service named `sshd.exe` and
        # it must not be touched.
        return _stop_orphans()
    try:
        with open(pidfile, "r", encoding="utf-8") as fh:
            pid = int(fh.read().strip())
    except (OSError, ValueError):
        return _stop_orphans()
    if not _pid_alive(pid):
        _forget_pid()
        return _stop_orphans()
    try:
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/F", "/PID", str(pid)],
                           capture_output=True)
        else:
            os.kill(pid, 15)
            # give it a moment, then insist
            for _ in range(20):
                if not _pid_alive(pid):
                    break
                time.sleep(0.1)
            if _pid_alive(pid):
                os.kill(pid, 9)
    except OSError:
        return False
    _forget_pid()
    return True


def _stop_orphans() -> bool:
    """Stop this project's sshd processes that have no pid file.

    THE COMMAND LINE IS THE HANDLE.  It names this project's config,
    and the SYSTEM sshd's command line does not, so the two are never
    confused.

    On Windows the image is `sshd.exe` for the user-level one and
    `sshd-session.exe` for a connection, so both names are matched.
    On Linux the process title changes to "sshd: /usr/sbin/sshd -f
    ...", so the config path is still in the command line and the
    match works there too.
    """
    import subprocess as _sp

    config = os.path.basename(paths.sshd_config())
    # THE REGEX FORM OF IT, for the PowerShell that searches for it.
    #
    # `-like` IS NOT USED, and it is not a style choice: in this
    # PowerShell the wildcard operator does not work AT ALL --
    #
    #     'abc.exe' -like 'abc%'   ->   False
    #
    # MEASURED: that is what it says, and `-eq` and `-match` both
    # work.  So a filter written with `-like` matches NOTHING, and
    # the count is zero and the cleanup does nothing -- and the
    # leftovers stay, holding the port.
    config_re = re.escape(config)

    if sys.platform == "win32":
        # THE LISTENER ONLY.  The per-connection children are
        # `sshd-session.exe` and they are `stop_sessions()`'s job --
        # a function that stops one thing should not stop another.
        find_ps = ("Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | "
                   "Where-Object { $_.Name -eq 'sshd.exe' -and "
                   f"$_.CommandLine -match '{config_re}' }} | "
                   "ForEach-Object { $_.ProcessId }")
    else:
        find_ps = (f"pgrep -f '{config}' 2>/dev/null || true")

    try:
        r = _sp.run(["powershell.exe", "-NoProfile", "-NonInteractive",
                     "-Command", find_ps] if sys.platform == "win32"
                    else ["sh", "-c", find_ps],
                    capture_output=True, text=True, errors="replace",
                    timeout=60)
    except (OSError, _sp.TimeoutExpired):
        return False

    pids = []
    for line in (r.stdout or "").splitlines():
        line = line.strip()
        if line.isdigit():
            pids.append(int(line))

    if not pids:
        return False

    for pid in pids:
        try:
            if sys.platform == "win32":
                _sp.run(["taskkill", "/F", "/PID", str(pid)],
                        capture_output=True, timeout=60)
            else:
                os.kill(pid, 15)
        except (OSError, _sp.TimeoutExpired):
            pass
    return True


def stop_sessions() -> int:
    """Stop the per-connection children, and say how many there were.

    THE LISTENER IS NOT ENOUGH.  On Windows the per-CONNECTION child
    is `sshd-session.exe`, and it is the one that holds the FORWARDED
    port open.  So killing the listener leaves the forwarded port
    held by a session that is still there -- and the next launch
    finds that port busy for no reason anybody can see.

    On Linux sshd's children die with the listener, so there is
    nothing to do and this returns 0.

    THE CHILDREN ARE FOUND BY THEIR COMMAND LINE, which names this
    project's config.  Never by the image name alone: the SYSTEM
    sshd is a service named `sshd.exe` and it must not be touched,
    and its sessions are named the same way.

    AND THE LISTENER IS NOT IN THE MATCH.  The name filter is
    `sshd-session%`, so it covers the per-connection children and
    nothing else.  The LISTENER is `sshd.exe`, and it is stopped by
    `stop()` -- which is a different function with a different job,
    and a function that stops one thing should not stop another.

    MEASURED: a filter of `sshd*` here killed the listener as well,
    and the tunnel went down in the middle of a test that was
    checking that it worked.
    """
    if sys.platform != "win32":
        return 0

    import subprocess as _sp

    config = os.path.basename(paths.sshd_config())
    # THE REGEX FORM OF IT, for the PowerShell that searches for it.
    #
    # `-like` IS NOT USED, and it is not a style choice: in this
    # PowerShell the wildcard operator does not work AT ALL --
    #
    #     'abc.exe' -like 'abc%'   ->   False
    #
    # MEASURED: that is what it says, and `-eq` and `-match` both
    # work.  So a filter written with `-like` matches NOTHING, and
    # the count is zero and the cleanup does nothing -- and the
    # leftovers stay, holding the port.
    config_re = re.escape(config)

    # HOW MANY THERE ARE FIRST, so the answer is the number that were
    # there and not the number that are left.  A count taken AFTER
    # the killing is always zero, and a function that always returns
    # zero cannot say that it did something.
    count_ps = ("(Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | "
                "Where-Object { $_.Name -match '^sshd-session' -and "
                f"$_.CommandLine -match '{config_re}' }} | "
                "Measure-Object).Count")

    try:
        r = _sp.run(["powershell.exe", "-NoProfile", "-NonInteractive",
                     "-Command", count_ps], capture_output=True, text=True,
                    errors="replace", timeout=60)
        n = int((r.stdout or "0").strip() or 0)
    except (OSError, ValueError, _sp.TimeoutExpired):
        return 0

    if not n:
        return 0

    # and kill them
    kill_ps = ("Get-CimInstance Win32_Process -ErrorAction SilentlyContinue | "
               "Where-Object { $_.Name -match '^sshd-session' -and "
               f"$_.CommandLine -match '{config_re}' }} | "
               "ForEach-Object { Stop-Process -Id $_.ProcessId -Force "
               "-ErrorAction SilentlyContinue }")
    try:
        _sp.run(["powershell.exe", "-NoProfile", "-NonInteractive",
                 "-Command", kill_ps], capture_output=True, text=True,
                errors="replace", timeout=60)
    except (OSError, _sp.TimeoutExpired):
        pass
    return n


def _forget_pid() -> None:
    """Remove the pid file, so a stopped sshd is not "running"."""
    try:
        os.remove(paths.pid_file())
    except OSError:
        pass


def port_busy(port: int, listen: str = "0.0.0.0") -> bool:
    """Is something already listening on that port?

    Worth saying out loud when it is: "the sshd did not start" is not
    an answer a person can act on, and "another process holds port
    10001" is.
    """
    import socket
    s = socket.socket()
    try:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        s.bind((listen, port))
        return False
    except OSError:
        return True
    finally:
        s.close()


def _pid_alive(pid: int) -> bool:
    """Is that process still running?

    os.kill(pid, 0) is a probe on POSIX but SIGNALISES on Windows, so
    tasklist is used there.
    """
    if sys.platform == "win32":
        r = subprocess.run(["tasklist", "/FI", f"PID eq {pid}"],
                           capture_output=True, text=True, errors="replace")
        return str(pid) in (r.stdout or "")
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False
