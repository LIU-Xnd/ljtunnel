"""Running a user-level sshd.

The system's own sshd is a service and it wants to be the only one. A
tunnel needs a second one, on its own port, with its own keys and its
own rules -- and it has to be runnable by an ordinary user, because the
thing that cannot be reached is not going to have root.

Both ends of OpenSSH can do that, and it is worth being explicit about
why each setting is there:

  UsePrivilegeSeparation no   Windows: the separation needs a privileged
                               helper, and a user-level sshd has none.
  UsePAM no                    Linux: PAM wants to authenticate against
                               the system, which is the service's job.
  StrictModes no              Both: the key directory is in the user's
                               own space, and the strict check wants
                               the SYSTEM sshd's layout.
  GatewayPorts clientspecified  The listen end only: without it the
                               forwarded port binds to loopback and
                               nobody off the machine can reach it.
  PidFile                      So "stop" can find the process without
                               guessing.
  AuthorizedKeysFile           The tunnel's own key list, so the user's
                               ~/.ssh/authorized_keys is not what
                               decides who gets in.

Nothing here touches the system's sshd, its service, its port 22, or
its configuration.
"""
from __future__ import annotations

import os
import subprocess
import sys
import time

from . import paths

# The lines that are the same on both ends. The listen end adds
# GatewayPorts; see the template below.
_TEMPLATE = """# ljtunnel -- this end's own sshd.
#
# Generated by ljtunnel. Edits are lost when it is regenerated, which
# is the point: the file is a rendering of the tunnel's state, not a
# thing to hand-edit.

Port {port}
ListenAddress {listen}
HostKey {host_key}
PidFile {pid_file}
LogLevel INFO

# A user-level sshd, not a service: there is no PAM to authenticate
# against, and the strict check wants the SYSTEM sshd's key layout.
#
# UsePrivilegeSeparation is WINDOWS ONLY. On OpenSSH 8.2 and later it
# is deprecated and every start prints a warning about it, and on
# Linux it is not needed at all -- a user-level sshd has nothing to
# separate into.
{win_only}UsePAM no

# The key directory is in the user's own space, not the layout the
# strict check wants.
StrictModes no

# Public keys only. A password over a forwarded port is a password
# sent to a machine you may not be able to see.
PasswordAuthentication no
PubkeyAuthentication yes
AuthorizedKeysFile {authorized_keys}

# The tunnel's own host key, so the user's ~/.ssh is not consulted.
HostKey {host_key}

{gateway}
# Forwarding: the listen end accepts a remote forward from a dialer;
# the dialer end does not need to accept one from anyone.
{forwarding}
"""


def sshd_path() -> str:
    """The sshd binary.

    On Windows it is in Program Files, which is not on PATH for an
    ordinary shell. On Linux it is in /usr/sbin, which IS on PATH for
    root and not for everybody.
    """
    if sys.platform == "win32":
        import shutil
        for p in (r"C:\Program Files\OpenSSH\sshd.exe",
                  r"C:\Program Files (x86)\OpenSSH\sshd.exe"):
            if os.path.isfile(p):
                return p
        found = shutil.which("sshd")
        if found:
            return found
        raise SystemExit(
            "sshd.exe not found. OpenSSH for Windows installs it into "
            "C:\\Program Files\\OpenSSH.")
    import shutil
    for p in ("/usr/sbin/sshd", "/usr/local/sbin/sshd"):
        if os.path.isfile(p):
            return p
    found = shutil.which("sshd")
    if found:
        return found
    raise SystemExit("sshd not found -- install openssh-server")


def ssh_path() -> str:
    """The ssh client binary."""
    if sys.platform == "win32":
        import shutil
        for p in (r"C:\Windows\System32\OpenSSH\ssh.exe",
                  r"C:\Program Files\OpenSSH\ssh.exe"):
            if os.path.isfile(p):
                return p
        found = shutil.which("ssh")
        if found:
            return found
        raise SystemExit("ssh.exe not found")
    import shutil
    found = shutil.which("ssh")
    if found:
        return found
    raise SystemExit("ssh not found -- install openssh-client")


def ssh_keygen_path() -> str:
    if sys.platform == "win32":
        import shutil
        for p in (r"C:\Program Files\OpenSSH\ssh-keygen.exe",
                  r"C:\Windows\System32\OpenSSH\ssh-keygen.exe"):
            if os.path.isfile(p):
                return p
        found = shutil.which("ssh-keygen")
        if found:
            return found
        raise SystemExit("ssh-keygen.exe not found")
    import shutil
    found = shutil.which("ssh-keygen")
    if found:
        return found
    raise SystemExit("ssh-keygen not found")


def write_config(port: int, listen: str = "0.0.0.0",
                 gateway_ports: bool = False,
                 allow_forwarding: bool = False) -> str:
    """Render the sshd config and return its path."""
    paths.ensure_dir(paths.state_dir())
    body = _TEMPLATE.format(
        port=port,
        listen=listen,
        host_key=paths.host_key(),
        pid_file=paths.pid_file(),
        authorized_keys=paths.authorized_keys(),
        win_only=("UsePrivilegeSeparation no\n"
                 if sys.platform == "win32" else ""),
        gateway=("GatewayPorts clientspecified\n"
                 if gateway_ports else ""),
        forwarding=("AllowTcpForwarding remote\n"
                    if allow_forwarding else
                    "AllowTcpForwarding no\n"),
    )
    path = paths.sshd_config()
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return path


def ensure_host_key() -> str:
    """Make this end's host key if it does not have one.

    The key is the identity a client sees when it connects, so it has
    to SURVIVE a restart: a new key every time would make every
    client complain about a changed host key.
    """
    key = paths.host_key()
    if os.path.isfile(key):
        return key
    paths.ensure_dir(paths.state_dir())
    r = subprocess.run(
        [ssh_keygen_path(), "-q", "-t", "ed25519", "-f", key, "-N", ""],
        capture_output=True, text=True, errors="replace")
    if r.returncode != 0:
        raise SystemExit(f"ssh-keygen failed: {(r.stdout + r.stderr).strip()}")
    try:
        os.chmod(key, 0o600)
    except OSError:
        pass
    return key


